// SafePaths are the files safe mode may write when the playbook sets no
// writePaths: dependency manifests and image references.
var SafePaths = []string{
	"**/Dockerfile", "**/Dockerfile.*", "**/*.Dockerfile", "**/Containerfile",
	"**/go.mod", "**/package.json", "**/requirements*.txt", "**/pyproject.toml",
	"**/Pipfile", "**/Gemfile", "**/pom.xml", "**/build.gradle", "**/build.gradle.kts",
	"**/Cargo.toml", "**/composer.json", "**/Chart.yaml", "**/values*.yaml",
	"**/kustomization.yaml",
}

// LockFiles are generated by package managers. The worker has none, so a
// lockfile the model writes is stale or invented: safe mode refuses them.
var LockFiles = []string{
	"**/go.sum", "**/package-lock.json", "**/yarn.lock", "**/pnpm-lock.yaml",
	"**/poetry.lock", "**/uv.lock", "**/Pipfile.lock", "**/Cargo.lock",
	"**/Gemfile.lock", "**/composer.lock", "**/Chart.lock",
}

// IgnoreFiles record scanner false positives, e.g. "CVE-2024-1234". One
// entry can mute a whole package type, so safe mode refuses them and full
// mode needs a writePaths pattern that names them (CheckWritePath).
var IgnoreFiles = []string{
	"**/.trivyignore", "**/.trivyignore.yaml", "**/.grype.yaml", "**/.snyk",
	"**/osv-scanner.toml", "**/*.vex.json", "**/*.openvex.json",
}

func matchAny(pats []string, p string) bool {
	for _, pat := range pats {
		if MatchPath(pat, p) {
			return true
		}
	}
	return false
}

// CheckSafeDiff fails unless every changed line differs from the old one
// only in versions and image digests:
//
//	version   an upgrade within the major version: v1.4.2 -> v1.5.0 ok,
//	          v1.4.2 -> v2.0.0, 3.20 -> 3.18 and 512Mi -> 1Gi refused
//	distro    only the patch level: alpine:3.20.1 -> 3.20.3 ok,
//	          alpine:3.18 -> 3.20 and ubuntu:22.04 -> 24.04 refused
//	digest    one @sha256:<64 hex> for another on an image reference
//
// New, deleted, renamed and binary files, lockfiles and ignore files are refused.
func CheckSafeDiff(patch diff.Patch) error {
	for _, fp := range patch.FilePatches() {
		if err := toFileDiff(fp).check(); err != nil {
			return fmt.Errorf("refused in safe mode: %w", err)
		}
	}
	return nil
}

type fileDiff struct {
	oldPath, newPath string
	binary           bool
	blocks           []block
}

// block is a run of removed lines followed by added lines.
type block struct{ del, add []string }

func (f *fileDiff) path() string {
	if f.newPath == "" {
		return f.oldPath
	}
	return f.newPath
}

func (f *fileDiff) check() error {
	p := f.path()
	switch {
	case matchAny(LockFiles, p) || matchAny(IgnoreFiles, p):
		return fmt.Errorf("%s: lockfiles and ignore files are not changed in safe mode", p)
	case f.oldPath != "" && f.newPath != "" && f.oldPath != f.newPath:
		return fmt.Errorf("%s: renamed from %s", f.newPath, f.oldPath)
	case f.newPath == "":
		return fmt.Errorf("%s: file deleted", p)
	case f.binary:
		return fmt.Errorf("%s: binary change", p)
	case f.oldPath == "":
		return fmt.Errorf("%s: new file", p)
	}
	for _, b := range f.blocks {
		if len(b.del) != len(b.add) {
			return fmt.Errorf("%s: adds or removes lines (-%d +%d); only versions in existing lines may change", p, len(b.del), len(b.add))
		}
		for i := range b.del {
			if err := checkLine(b.del[i], b.add[i]); err != nil {
				return fmt.Errorf("%s: %q -> %q: %w", p, b.del[i], b.add[i], err)
			}
		}
	}
	return nil
}

// toFileDiff groups a go-git file patch into blocks: each run of deleted
// lines with the added lines right after it.
func toFileDiff(fp diff.FilePatch) *fileDiff {
	from, to := fp.Files()
	f := &fileDiff{binary: fp.IsBinary()}
	if from != nil {
		f.oldPath = from.Path()
	}
	if to != nil {
		f.newPath = to.Path()
	}
	var cur *block
	flush := func() {
		if cur != nil {
			f.blocks = append(f.blocks, *cur)
		}
		cur = nil
	}
	for _, c := range fp.Chunks() {
		switch c.Type() {
		case diff.Delete:
			if cur != nil && len(cur.add) > 0 {
				flush()
			}
			if cur == nil {
				cur = &block{}
			}
			cur.del = append(cur.del, chunkLines(c)...)
		case diff.Add:
			if cur == nil {
				cur = &block{}
			}
			cur.add = append(cur.add, chunkLines(c)...)
		default:
			flush()
		}
	}
	flush()
	return f
}

// chunkLines splits a chunk into lines, e.g. "a\nb\n" -> [a b].
func chunkLines(c diff.Chunk) []string {
	return strings.Split(strings.TrimSuffix(c.Content(), "\n"), "\n")
}

// versionRE matches "3.18", "v1.2.3", "3.1.4-r5", "20.11-alpine3.19" and
// "1.0.0+incompatible". A match followed by a letter, like "1.5Gi", is a
// quantity, not a version.
var versionRE = regexp.MustCompile(`v?\d+(?:\.\d+)+(?:[-+~_][0-9A-Za-z]+(?:\.[0-9A-Za-z]+)*)*`)

var digitsRE = regexp.MustCompile(`\d+`)

// digestRE is an image digest, e.g. "@sha256:" and 64 hex digits.
var digestRE = regexp.MustCompile(`@sha256:[0-9a-f]{64}`)

// distroRE matches the text before a distro image tag, e.g. "FROM alpine:"
// or "image: docker.io/library/ubuntu:". Distro releases do not follow
// semver: 3.18 -> 3.20 is two releases, so the first two numbers are the major.
var distroRE = regexp.MustCompile(`(^|[/\s"'=])(alpine|debian|ubuntu|fedora|centos|rockylinux|almalinux|amazonlinux|oraclelinux|opensuse/leap|ubi[0-9]*(-minimal|-micro)?):$`)

type tokenKind int

const (
	text tokenKind = iota
	version
	digest
)

type token struct {
	text string
	kind tokenKind
}

// tokenize splits a line into digests, versions and the text between them,
// e.g. "FROM alpine:3.20@sha256:ab..." -> "FROM alpine:", "3.20", "@sha256:ab...".
// A digest counts only right after an image name and with exactly 64 hex
// digits; anything else stays text.
func tokenize(s string) []token {
	var out []token
	last := 0
	for _, m := range digestRE.FindAllStringIndex(s, -1) {
		if m[0] == 0 || !isNameChar(s[m[0]-1]) || (m[1] < len(s) && isHex(s[m[1]])) {
			continue
		}
		out = append(out, tokenizeVersions(s[last:m[0]])...)
		out = append(out, token{text: s[m[0]:m[1]], kind: digest})
		last = m[1]
	}
	return append(out, tokenizeVersions(s[last:])...)
}

// tokenizeVersions splits s into versions and the text between them.
func tokenizeVersions(s string) []token {
	var out []token
	last := 0
	for _, m := range versionRE.FindAllStringIndex(s, -1) {
		if m[1] < len(s) && isLetter(s[m[1]]) {
			continue
		}
		if m[0] > last {
			out = append(out, token{text: s[last:m[0]]})
		}
		out = append(out, token{text: s[m[0]:m[1]], kind: version})
		last = m[1]
	}
	if last < len(s) {
		out = append(out, token{text: s[last:]})
	}
	return out
}

func isHex(c byte) bool { return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') }

// isNameChar reports a character of an image name or tag, e.g. in "alpine:3.20".
func isNameChar(c byte) bool {
	return isLetter(c) || (c >= '0' && c <= '9') || c == '.' || c == '-' || c == '_' || c == '/' || c == ':'
}

func isLetter(c byte) bool { return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') }

// checkLine allows old -> new when only versions and digests changed: each
// version upgraded within its major version, each digest replaced by another.
func checkLine(old, new string) error {
	a, b := tokenize(old), tokenize(new)
	if len(a) != len(b) {
		return fmt.Errorf("more than a version changed")
	}
	for i := range a {
		if a[i].kind != b[i].kind {
			return fmt.Errorf("more than a version changed")
		}
		if a[i].text == b[i].text || a[i].kind == digest {
			continue
		}
		if a[i].kind == text {
			return fmt.Errorf("more than a version changed")
		}
		distro := i > 0 && a[i-1].kind == text && distroRE.MatchString(a[i-1].text)
		if err := checkUpgrade(a[i].text, b[i].text, distro); err != nil {
			return err
		}
	}
	return nil
}

// checkUpgrade allows "3.18" -> "3.20.3" and "3.1.4-r5" -> "3.1.4-r6", and
// refuses major bumps, downgrades and a different suffix ("-alpine" ->
// "-debian"). For 0.x the minor version counts as major, as in semver; for
// a distro image (distro) the first two numbers are the major, so only the
// patch level may change: alpine 3.20.1 -> 3.20.3.
func checkUpgrade(old, new string, distro bool) error {
	if looksLikeIPv4(old) || looksLikeIPv4(new) {
		return fmt.Errorf("%s -> %s looks like an IP address, not a version", old, new)
	}
	oc, osuf := splitVersion(old)
	nc, nsuf := splitVersion(new)
	if digitsRE.ReplaceAllString(osuf, "#") != digitsRE.ReplaceAllString(nsuf, "#") {
		return fmt.Errorf("version %s -> %s changes the variant", old, new)
	}
	major := 1
	if oc[0] == "0" || distro {
		major = 2
	}
	// versionRE needs a dot, so each core has at least two parts.
	for i := 0; i < major; i++ {
		if cmpNum(oc[i], nc[i]) != 0 {
			return fmt.Errorf("version %s -> %s is a major version change", old, new)
		}
	}
	oldNums := append(padded(oc, len(nc)), digitsRE.FindAllString(osuf, -1)...)
	newNums := append(padded(nc, len(oc)), digitsRE.FindAllString(nsuf, -1)...)
	for i := range oldNums {
		switch cmpNum(oldNums[i], newNums[i]) {
		case -1:
			return nil
		case 1:
			return fmt.Errorf("version %s -> %s is a downgrade", old, new)
		}
	}
	return nil
}

// looksLikeIPv4 reports four numbers of at most 255 and nothing else, e.g.
// "10.0.0.1". Safe mode refuses those rather than treat them as versions.
func looksLikeIPv4(v string) bool {
	parts := strings.Split(v, ".")
	if len(parts) != 4 {
		return false
	}
	for _, p := range parts {
		if n, err := strconv.Atoi(p); err != nil || n > 255 {
			return false
		}
	}
	return true
}

// splitVersion splits "v3.1.4-r5" into ["3" "1" "4"] and "-r5".
func splitVersion(v string) (core []string, suffix string) {
	v = strings.TrimPrefix(v, "v")
	end := strings.IndexAny(v, "-+~_")
	if end < 0 {
		end = len(v)
	}
	return strings.Split(v[:end], "."), v[end:]
}

func padded(s []string, n int) []string {
	out := append([]string(nil), s...)
	for len(out) < n {
		out = append(out, "0")
	}
	return out
}

// cmpNum compares decimal strings of any length, e.g. "9" < "10".
func cmpNum(a, b string) int {
	a, b = strings.TrimLeft(a, "0"), strings.TrimLeft(b, "0")
	if len(a) != len(b) {
		if len(a) < len(b) {
			return -1
		}
		return 1
	}
	return strings.Compare(a, b)
}
